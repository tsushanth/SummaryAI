import { describe, it, expect } from 'vitest';
import { actionItemLine, renderSummaryEmail, summarySubject } from '../src/lib/summaryEmail.js';

const base = {
  title: 'Weekly sync',
  recordedAt: '2026-10-28T22:00:00.000Z',
  durationSeconds: 5040,
  summary: 'First paragraph.\n\nSecond paragraph.',
  keyPoints: ['Point A'],
  actionItems: ['Send deck (Ana, due Friday)'],
  senderEmail: 'owner@example.com',
  webAppUrl: 'https://meetingmind.org/',
};

describe('renderSummaryEmail', () => {
  it('renders title, sections, sender line and the MeetingMind footer link in html and text', () => {
    const { html, text } = renderSummaryEmail(base);
    for (const out of [html, text]) {
      expect(out).toContain('Weekly sync');
      expect(out).toContain('First paragraph.');
      expect(out).toContain('Point A');
      expect(out).toContain('Send deck');
      expect(out).toContain('owner@example.com');
    }
    expect(html).toContain('href="https://meetingmind.org"');
    expect(html).toContain('1 h 24 min');
    expect(text).toContain('Summary generated by MeetingMind, https://meetingmind.org');
  });

  it('escapes HTML in the title, summary, note and action items', () => {
    const { html } = renderSummaryEmail({
      ...base,
      title: '<script>alert(1)</script>',
      summary: '<img src=x onerror=alert(1)>',
      note: '"><b>hi</b>',
      actionItems: ['<a href="javascript:x">go</a>'],
    });
    expect(html).not.toContain('<script>');
    expect(html).not.toContain('<img');
    expect(html).not.toContain('<b>hi</b>');
    expect(html).not.toContain('<a href="javascript:x">');
    expect(html).toContain('&lt;script&gt;');
  });

  it('omits empty sections and the note when absent', () => {
    const { html } = renderSummaryEmail({ ...base, keyPoints: [], actionItems: [] });
    expect(html).not.toContain('Key points');
    expect(html).not.toContain('Action items');
    expect(html).not.toContain('border-left:3px');
  });
});

describe('actionItemLine', () => {
  it('handles strings and task objects with assignee and due date', () => {
    expect(actionItemLine('  do it ')).toBe('do it');
    expect(actionItemLine({ task: 'Ship', assignee: 'Ana', due_date: '2026-11-01' })).toBe('Ship (Ana, due 2026-11-01)');
    expect(actionItemLine({ text: 'Plain' })).toBe('Plain');
    expect(actionItemLine({})).toBeNull();
    expect(actionItemLine(null)).toBeNull();
  });
});

describe('summarySubject', () => {
  it('is single-line and capped', () => {
    expect(summarySubject('Hello\r\nBcc: evil@example.com')).not.toMatch(/[\r\n]/);
    expect(summarySubject('x'.repeat(400)).length).toBe(150);
    expect(summarySubject('   ')).toBe('Meeting summary: Meeting');
  });
});
